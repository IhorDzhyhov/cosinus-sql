SELECT Nazwa, Cena, Ilosc FROM PRODUKTY WHERE Ilosc IN (4, 5, 6);
SELECT Nazwa, Cena, Data_produkcji FROM PRODUKTY WHERE DAY(Data_produkcji) BETWEEN 1 AND 10;
SELECT COUNT(*) AS LICZBA FROM PRODUKTY WHERE MONTH(Data_produkcji) = 2;
SELECT * FROM PRODUKTY ORDER BY Cena DESC LIMIT 5;
SELECT * FROM PRODUKTY ORDER BY Cena DESC LIMIT 3;
SELECT * FROM PRODUKTY WHERE YEAR(Data_produkcji) > 2012 AND Cena BETWEEN 50 AND 200;
SELECT REPLACE(Nazwa, 'K', 'i') AS PRODUKTY FROM PRODUKTY;
SELECT Nazwa, SUBSTRING(Nazwa, 1, 2) AS PIERWSZE, SUBSTRING(Nazwa, LENGTH(Nazwa)-1, 2) AS OSTATNIE FROM PRODUKTY;
SELECT Nazwa, Cena, UPPER(Nazwa) AS `NAZWA DRUKOWANYMI` FROM PRODUKTY;
SELECT *, Cena * 1.10 AS `NOWA CENA` FROM PRODUKTY;
SELECT SUM(Cena * Ilosc) AS SUMA FROM PRODUKTY;
SELECT MAX(Cena) AS NAJWIEKSZA, MIN(Cena) AS NAJMNIEJSZA, AVG(Cena) AS SREDNIA FROM PRODUKTY;
SELECT *, CHAR_LENGTH(Nazwa) AS `DLUGOSC WYRAZU` FROM PRODUKTY;
SELECT *, Cena * 2 AS ILOCZYN FROM PRODUKTY;
SELECT NOW() AS `BIEZACA DATA`;
SELECT DAYOFYEAR(Data_produkcji) AS `DZIEN ROKU` FROM PRODUKTY;
CREATE VIEW PERSPEKTYWA AS SELECT Nazwa, Cena * Ilosc AS CENA FROM PRODUKTY;
SELECT Nazwa, Cena FROM PRODUKTY WHERE Cena > (SELECT AVG(Cena) FROM PRODUKTY);
