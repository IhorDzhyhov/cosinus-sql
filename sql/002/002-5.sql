CREATE TABLE PRODUKTY (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    Nazwa VARCHAR(50),
    Cena DECIMAL(10,2),
    Ilosc INT,
    Data_produkcji DATE
);

